export interface Coupon {
    id: string;
    code: string;
    title: string;
    category: "monthly" | "major_holiday" | "observance" | "custom";
    discountPercent: number;
    startDate: string; // YYYY-MM-DD
    endDate: string; // YYYY-MM-DD
    status: "active" | "upcoming" | "expired" | "inactive";
    isActiveToggle?: boolean; // Admin manual active toggle (true/false)
    description?: string;
    isAutoGenerated?: boolean;
    rowNumber?: number;
}

// 3-letter Month abbreviations
const MONTH_ABBR = [
    "JAN",
    "FEB",
    "MAR",
    "APR",
    "MAY",
    "JUN",
    "JUL",
    "AUG",
    "SEP",
    "OCT",
    "NOV",
    "DEC",
];

// Seeded pseudo-random digit generator based on string key
// Guarantees consistent 3-digit code for the same coupon key across refreshes
function generateCodeDigits(seedKey: string): string {
    let hash = 0;
    for (let i = 0; i < seedKey.length; i++) {
        hash = (hash << 5) - hash + seedKey.charCodeAt(i);
        hash |= 0;
    }
    const absHash = Math.abs(hash);
    const num = (absHash % 900) + 100; // between 100 and 999
    return num.toString();
}

// Helper: Format Date to YYYY-MM-DD
function formatDate(d: Date): string {
    const year = d.getFullYear();
    const month = String(d.getMonth() + 1).padStart(2, "0");
    const day = String(d.getDate()).padStart(2, "0");
    return `${year}-${month}-${day}`;
}

// Helper: Add days to date
function addDays(d: Date, days: number): Date {
    const res = new Date(d);
    res.setDate(res.getDate() + days);
    return res;
}

// Helper: Get nth day of week in month (e.g., 4th Thursday in November)
// dayOfWeek: 0 = Sunday, 1 = Monday, ..., 4 = Thursday, etc.
function getNthDayOfWeek(year: number, month: number, dayOfWeek: number, n: number): Date {
    const date = new Date(year, month, 1);
    let count = 0;
    while (date.getMonth() === month) {
        if (date.getDay() === dayOfWeek) {
            count++;
            if (count === n) {
                return new Date(date);
            }
        }
        date.setDate(date.getDate() + 1);
    }
    return new Date(year, month, 1);
}

// Helper: Get last day of week in month (e.g., Last Monday in May - Memorial Day)
function getLastDayOfWeek(year: number, month: number, dayOfWeek: number): Date {
    const date = new Date(year, month + 1, 0); // last day of month
    while (date.getDay() !== dayOfWeek) {
        date.setDate(date.getDate() - 1);
    }
    return new Date(date);
}

// Computus algorithm for Easter Sunday (Western Church / USA Calendar)
function getEasterSunday(year: number): Date {
    const a = year % 19;
    const b = Math.floor(year / 100);
    const c = year % 100;
    const d = Math.floor(b / 4);
    const e = b % 4;
    const f = Math.floor((b + 8) / 25);
    const g = Math.floor((b - f + 1) / 3);
    const h = (19 * a + b - d - g + 15) % 30;
    const i = Math.floor(c / 4);
    const k = c % 4;
    const l = (32 + 2 * e + 2 * i - h - k) % 7;
    const m = Math.floor((a + 11 * h + 22 * l) / 451);
    const month = Math.floor((h + l - 7 * m + 114) / 31) - 1; // 0-indexed (March=2, April=3)
    const day = ((h + l - 7 * m + 114) % 31) + 1;
    return new Date(year, month, day);
}

// Hanukkah start dates lookup for 2024 - 2030 (Starts at sunset, holiday on this day)
const HANUKKAH_DATES: Record<number, { month: number; day: number }> = {
    2024: { month: 11, day: 25 }, // Dec 25
    2025: { month: 11, day: 14 }, // Dec 14
    2026: { month: 11, day: 4 },  // Dec 4
    2027: { month: 11, day: 24 }, // Dec 24
    2028: { month: 11, day: 12 }, // Dec 12
    2029: { month: 11, day: 2 },  // Dec 2
    2030: { month: 11, day: 20 }, // Dec 20
};

function getHanukkahDate(year: number): Date {
    if (HANUKKAH_DATES[year]) {
        return new Date(year, HANUKKAH_DATES[year].month, HANUKKAH_DATES[year].day);
    }
    // Fallback: early December
    return new Date(year, 11, 10);
}

/**
 * Generate all monthly, major holiday, and observance coupons for a given year
 */
export function generateYearCoupons(year: number): Coupon[] {
    const coupons: Coupon[] = [];

    // 1. Monthly Coupons: 10% OFF
    // Code: WFM + 3-letter month + 3 random digits (e.g. WFMOCT482)
    // Starts: 1st of month, Total validity: 20 days
    for (let m = 0; m < 12; m++) {
        const monthAbbr = MONTH_ABBR[m];
        const seedKey = `MONTHLY-${year}-${monthAbbr}`;
        const digits = generateCodeDigits(seedKey);
        const code = `WFM${monthAbbr}${digits}`;

        const startDateObj = new Date(year, m, 1);
        const endDateObj = addDays(startDateObj, 19); // 20 days total (day 1 to day 20)

        coupons.push({
            id: `monthly-${year}-${m + 1}`,
            code,
            title: `${new Date(year, m, 1).toLocaleString("en-US", { month: "long" })} Monthly Offer`,
            category: "monthly",
            discountPercent: 10,
            startDate: formatDate(startDateObj),
            endDate: formatDate(endDateObj),
            status: "active",
            isActiveToggle: true,
            isAutoGenerated: true,
            description: "10% off monthly rental booking coupon.",
        });
    }

    // 2. Six Major U.S. Holidays: 25% OFF
    // Rule: Starts 5 days before with total validity of 20 days (starts holiday - 5 days, ends holiday + 14 days)
    const majorHolidays: Array<{
        idKey: string;
        name: string;
        getDate: (y: number) => Date;
        codePrefix: string;
    }> = [
        {
            idKey: "new-years-day",
            name: "New Year's Day",
            getDate: (y) => new Date(y, 0, 1),
            codePrefix: "WFMNEW",
        },
        {
            idKey: "memorial-day",
            name: "Memorial Day",
            getDate: (y) => getLastDayOfWeek(y, 4, 1), // Last Monday of May
            codePrefix: "WFMMEM",
        },
        {
            idKey: "independence-day",
            name: "Independence Day (4th of July)",
            getDate: (y) => new Date(y, 6, 4), // July 4
            codePrefix: "WFMJUL",
        },
        {
            idKey: "labor-day",
            name: "Labor Day",
            getDate: (y) => getNthDayOfWeek(y, 8, 1, 1), // 1st Monday of September
            codePrefix: "WFMLAB",
        },
        {
            idKey: "thanksgiving",
            name: "Thanksgiving",
            getDate: (y) => getNthDayOfWeek(y, 10, 4, 4), // 4th Thursday of November
            codePrefix: "WFMTHX",
        },
        {
            idKey: "christmas",
            name: "Christmas",
            getDate: (y) => new Date(y, 11, 25), // Dec 25
            codePrefix: "WFMCHX",
        },
    ];

    for (const h of majorHolidays) {
        const holidayDate = h.getDate(year);
        const startDateObj = addDays(holidayDate, -5); // Starts 5 days before
        const endDateObj = addDays(startDateObj, 19);  // 20 days total validity
        const seedKey = `MAJOR-${h.idKey}-${year}`;
        const digits = generateCodeDigits(seedKey);
        const code = `${h.codePrefix}${digits}`;

        coupons.push({
            id: `major-${h.idKey}-${year}`,
            code,
            title: `${h.name} Special`,
            category: "major_holiday",
            discountPercent: 25,
            startDate: formatDate(startDateObj),
            endDate: formatDate(endDateObj),
            status: "active",
            isActiveToggle: true,
            isAutoGenerated: true,
            description: `25% off for ${h.name} holiday celebrations.`,
        });
    }

    // 3. Other Holidays & Observances: 15% OFF
    // Rule: Starts 5 days before with total validity of 20 days
    const observances: Array<{
        idKey: string;
        name: string;
        getDate: (y: number) => Date;
        codePrefix: string;
    }> = [
        {
            idKey: "valentines-day",
            name: "Valentine's Day",
            getDate: (y) => new Date(y, 1, 14), // Feb 14
            codePrefix: "WFMVAL",
        },
        {
            idKey: "easter",
            name: "Easter",
            getDate: (y) => getEasterSunday(y),
            codePrefix: "WFMEST",
        },
        {
            idKey: "mothers-day",
            name: "Mother's Day",
            getDate: (y) => getNthDayOfWeek(y, 4, 0, 2), // 2nd Sunday in May
            codePrefix: "WFMMOM",
        },
        {
            idKey: "fathers-day",
            name: "Father's Day",
            getDate: (y) => getNthDayOfWeek(y, 5, 0, 3), // 3rd Sunday in June
            codePrefix: "WFMDAD",
        },
        {
            idKey: "halloween",
            name: "Halloween",
            getDate: (y) => new Date(y, 9, 31), // Oct 31
            codePrefix: "WFMHAL",
        },
        {
            idKey: "veterans-day",
            name: "Veterans Day",
            getDate: (y) => new Date(y, 10, 11), // Nov 11
            codePrefix: "WFMVET",
        },
        {
            idKey: "hanukkah",
            name: "Hanukkah",
            getDate: (y) => getHanukkahDate(year),
            codePrefix: "WFMHAN",
        },
    ];

    for (const obs of observances) {
        const obsDate = obs.getDate(year);
        const startDateObj = addDays(obsDate, -5); // Starts 5 days before
        const endDateObj = addDays(startDateObj, 19); // 20 days total validity
        const seedKey = `OBS-${obs.idKey}-${year}`;
        const digits = generateCodeDigits(seedKey);
        const code = `${obs.codePrefix}${digits}`;

        coupons.push({
            id: `obs-${obs.idKey}-${year}`,
            code,
            title: `${obs.name} Observance`,
            category: "observance",
            discountPercent: 15,
            startDate: formatDate(startDateObj),
            endDate: formatDate(endDateObj),
            status: "active",
            isActiveToggle: true,
            isAutoGenerated: true,
            description: `15% off for ${obs.name} celebration.`,
        });
    }

    return coupons;
}

/**
 * Determine dynamic status of coupon based on current date
 */
export function calculateCouponStatus(
    startDateStr: string,
    endDateStr: string,
    isActiveToggle: boolean = true,
    now: Date = new Date(),
): "active" | "upcoming" | "expired" | "inactive" {
    if (!isActiveToggle) {
        return "inactive";
    }

    const todayStr = formatDate(now);
    if (todayStr < startDateStr) {
        return "upcoming";
    }
    if (todayStr > endDateStr) {
        return "expired";
    }
    return "active";
}

/**
 * Check if an expired coupon should still be displayed based on 90-day retention rule
 */
export function isWithin90DaysOfExpiration(endDateStr: string, now: Date = new Date()): boolean {
    const end = new Date(endDateStr);
    const diffTime = now.getTime() - end.getTime();
    const diffDays = diffTime / (1000 * 3600 * 24);
    return diffDays <= 90;
}

/**
 * Get comprehensive list of auto-generated coupons spanning previous, current, and next year
 */
export function getAllAutoCoupons(baseDate: Date = new Date()): Coupon[] {
    const currentYear = baseDate.getFullYear();
    const prevYearCoupons = generateYearCoupons(currentYear - 1);
    const currYearCoupons = generateYearCoupons(currentYear);
    const nextYearCoupons = generateYearCoupons(currentYear + 1);

    const all = [...prevYearCoupons, ...currYearCoupons, ...nextYearCoupons];

    return all.map((c) => ({
        ...c,
        status: calculateCouponStatus(c.startDate, c.endDate, c.isActiveToggle, baseDate),
    }));
}

/**
 * CSV parse helper respecting quotes
 */
export function parseCsv(text: string): string[][] {
    const rows: string[][] = [];
    let currentRow: string[] = [];
    let currentCell = "";
    let insideQuotes = false;

    for (let i = 0; i < text.length; i++) {
        const char = text[i];
        const nextChar = text[i + 1];

        if (char === '"') {
            if (insideQuotes && nextChar === '"') {
                currentCell += '"';
                i++;
            } else {
                insideQuotes = !insideQuotes;
            }
        } else if (char === "," && !insideQuotes) {
            currentRow.push(currentCell.trim());
            currentCell = "";
        } else if ((char === "\r" || char === "\n") && !insideQuotes) {
            if (char === "\r" && nextChar === "\n") {
                i++;
            }
            currentRow.push(currentCell.trim());
            if (currentRow.some((c) => c !== "")) {
                rows.push(currentRow);
            }
            currentRow = [];
            currentCell = "";
        } else {
            currentCell += char;
        }
    }

    if (currentCell.length > 0 || currentRow.length > 0) {
        currentRow.push(currentCell.trim());
        if (currentRow.some((c) => c !== "")) {
            rows.push(currentRow);
        }
    }

    return rows;
}

export const GOOGLE_SHEET_COUPONS_CSV_URL =
    "https://docs.google.com/spreadsheets/d/16dhtw1POBIeifrAEk0ZqmH3jV8s20quo9Si3GfebifE/gviz/tq?tqx=out:csv&sheet=Coupons";

/**
 * Fetch and merge Google Sheet "Coupons" tab with automatic USA calendar generator
 */
export async function fetchAllCoupons(): Promise<Coupon[]> {
    const autoCoupons = getAllAutoCoupons();
    const couponMap = new Map<string, Coupon>();

    // Index auto-generated by uppercase code
    for (const c of autoCoupons) {
        couponMap.set(c.code.toUpperCase().trim(), c);
    }

    try {
        const resp = await fetch(GOOGLE_SHEET_COUPONS_CSV_URL);
        if (resp.ok) {
            const csvText = await resp.text();
            const rows = parseCsv(csvText);

            if (rows.length > 1) {
                const headers = rows[0].map((h) => h.toLowerCase().trim());
                const getIndex = (name: string) => headers.indexOf(name.toLowerCase());

                const idIdx = getIndex("coupon id") !== -1 ? getIndex("coupon id") : getIndex("id");
                const codeIdx = getIndex("code");
                const titleIdx = getIndex("title");
                const catIdx = getIndex("category");
                const discountIdx = getIndex("discount percent") !== -1 ? getIndex("discount percent") : getIndex("discount");
                const startIdx = getIndex("start date");
                const endIdx = getIndex("end date");
                const statusIdx = getIndex("status");
                const descIdx = getIndex("description");

                for (let i = 1; i < rows.length; i++) {
                    const row = rows[i];
                    if (!row || row.length === 0) continue;

                    const code = (codeIdx !== -1 ? row[codeIdx] : "")?.trim().toUpperCase();
                    if (!code) continue;

                    const discountRaw = discountIdx !== -1 ? parseFloat(row[discountIdx].replace(/[^0-9.]/g, "")) || 10 : 10;
                    const startDate = (startIdx !== -1 ? row[startIdx] : "")?.trim();
                    const endDate = (endIdx !== -1 ? row[endIdx] : "")?.trim();
                    const statusRaw = (statusIdx !== -1 ? row[statusIdx] : "")?.trim().toLowerCase();
                    const title = (titleIdx !== -1 ? row[titleIdx] : "")?.trim() || code;
                    const cat = (catIdx !== -1 ? row[catIdx] : "")?.trim().toLowerCase() as any;
                    const id = (idIdx !== -1 ? row[idIdx] : "")?.trim() || `coupon-${i}`;
                    const desc = (descIdx !== -1 ? row[descIdx] : "")?.trim();

                    const isActiveToggle = statusRaw !== "inactive" && statusRaw !== "disabled";

                    // Merge or create custom coupon
                    const existing = couponMap.get(code);
                    if (existing) {
                        couponMap.set(code, {
                            ...existing,
                            title: title || existing.title,
                            discountPercent: discountRaw > 0 ? discountRaw : existing.discountPercent,
                            startDate: startDate || existing.startDate,
                            endDate: endDate || existing.endDate,
                            isActiveToggle,
                            status: calculateCouponStatus(
                                startDate || existing.startDate,
                                endDate || existing.endDate,
                                isActiveToggle,
                            ),
                            rowNumber: i + 1,
                        });
                    } else {
                        couponMap.set(code, {
                            id,
                            code,
                            title,
                            category: cat || "custom",
                            discountPercent: discountRaw,
                            startDate,
                            endDate,
                            isActiveToggle,
                            status: calculateCouponStatus(startDate, endDate, isActiveToggle),
                            description: desc,
                            isAutoGenerated: false,
                            rowNumber: i + 1,
                        });
                    }
                }
            }
        }
    } catch (e) {
        console.warn("Could not load Google Sheet Coupons tab, falling back to dynamic generator:", e);
    }

    return Array.from(couponMap.values());
}
